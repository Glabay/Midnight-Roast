CREATE TABLE if not exists users (
    id VARCHAR(255) PRIMARY KEY,
    email VARCHAR(255) NOT NULL,
    nickname VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    status VARCHAR(255) NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT uq_users_nickname UNIQUE (nickname)
);

CREATE TABLE if not exists user_role (
    uid BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL,
    role VARCHAR(255) NOT NULL
);

CREATE INDEX idx_user_role_email_lower ON user_role (lower(email));

CREATE TABLE if not exists auth_refresh_token (
    id UUID PRIMARY KEY,
    user_email VARCHAR(255) NOT NULL,
    token_hash VARCHAR(128) NOT NULL UNIQUE,
    issued_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    revoked_at TIMESTAMP WITHOUT TIME ZONE,
    replaced_by UUID,
    user_agent VARCHAR(255),
    ip VARCHAR(64)
);

CREATE INDEX idx_auth_refresh_token_active_user_email
    ON auth_refresh_token (user_email)
    WHERE revoked_at IS NULL;

CREATE INDEX idx_auth_refresh_token_expires_at
    ON auth_refresh_token (expires_at);